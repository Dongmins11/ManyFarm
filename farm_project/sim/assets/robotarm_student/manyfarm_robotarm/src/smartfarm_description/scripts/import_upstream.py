#!/usr/bin/env python3
"""Regenerate namespaced Xacro fragments and copy referenced meshes; upstream stays untouched."""
import copy
import hashlib
import json
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET
import xacro

PKG = Path(__file__).resolve().parents[1]
WS = PKG.parents[1]
NS = 'http://www.ros.org/wiki/xacro'
ET.register_namespace('xacro', NS)
manifest = {}

def record(path):
    manifest[str(path.relative_to(WS))] = hashlib.sha256(path.read_bytes()).hexdigest()

def save(root, path):
    ET.indent(root)
    path.write_text('<?xml version="1.0"?>\n<!-- Generated by import_upstream.py, 2026-09-14. Source unchanged; mesh paths and names adapted. -->\n' + ET.tostring(root, encoding='unicode') + '\n')

def copy_mesh(src, subpath):
    target = PKG / 'meshes' / subpath
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, target)
    record(src)
    return '${mesh_root}/' + str(subpath)

base_path = WS / 'vic_pinky-main/vicpinky_description/urdf/robot_core.xacro'
for p in [base_path, base_path.with_name('inertial_macros.xacro')]: record(p)
base = ET.fromstring(xacro.process_file(str(base_path)).toxml())
for mesh in base.iter('mesh'):
    relative = Path(mesh.get('filename').split('/meshes/', 1)[1])
    mesh.set('filename', copy_mesh(base_path.parents[1] / 'meshes' / relative, Path('vicpinky') / relative))
# Macro confines upstream material names to a single expansion.
base_out = ET.Element('robot')
macro = ET.SubElement(base_out, f'{{{NS}}}macro', {'name':'vicpinky_base', 'params':''})
macro.extend(list(base))
save(base_out, PKG/'urdf/generated/vicpinky.xacro')

arm_path = WS / 'SO-ARM100-main/Simulation/SO101/so101_new_calib.urdf'
record(arm_path)
arm = ET.parse(arm_path).getroot()
arm_out = ET.Element('robot')
macro = ET.SubElement(arm_out, f'{{{NS}}}macro', {'name':'so101_arm', 'params':'prefix'})
for item in arm:
    # No ros1 SimpleTransmission / hardware plugin in a geometry-only asset.
    if item.tag not in ('link','joint','material'): continue
    item = copy.deepcopy(item)
    for e in item.iter():
        if e.tag in ('link','joint','material') and 'name' in e.attrib:
            e.set('name', '${prefix}' + e.get('name'))
        if e.tag in ('parent','child'):
            e.set('link', '${prefix}' + e.get('link'))
        if e.tag == 'mimic': e.set('joint', '${prefix}' + e.get('joint'))
        if e.tag == 'mesh':
            rel = Path(e.get('filename'))
            e.set('filename', copy_mesh(arm_path.parent/rel, Path('so101')/rel.name))
    macro.append(item)
save(arm_out, PKG/'urdf/generated/so101.xacro')
optional = WS/'SO-ARM100-main/Optional'
for source, target in [
    ('Wrist_Cam_Mount_RealSense_D435/stl/Wrist_cam_mount_RealSense_D435.stl', 'd435_wrist_mount.stl'),
    ('Overhead_Cam_Mount_32x32_UVC_Module/stl/cam_mount_middle.stl', 'overhead_post.stl'),
]:
    copy_mesh(optional/source, Path('mounts')/target)
shutil.copy2(WS/'SO-ARM100-main/LICENSE', PKG/'licenses/SO-ARM100-Apache-2.0.txt')
(PKG/'config/upstream_sha256.json').write_text(json.dumps(manifest, indent=2)+'\n')
print(f'Imported {len(manifest)} source files without modifying originals.')
